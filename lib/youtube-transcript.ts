const MAX_TRANSCRIPT_CHARS = 7500;

export function youtubeVideoId(input: string): string | null {
  try {
    const url = new URL(input);
    const host = url.hostname.replace(/^www\./, "").toLowerCase();
    if (host === "youtu.be") {
      const id = url.pathname.split("/").filter(Boolean)[0] ?? "";
      return isVideoId(id) ? id : null;
    }
    if (host === "youtube.com" || host === "m.youtube.com" || host === "music.youtube.com") {
      if (url.pathname.startsWith("/shorts/") || url.pathname.startsWith("/embed/") || url.pathname.startsWith("/live/")) {
        const id = url.pathname.split("/")[2] ?? "";
        return isVideoId(id) ? id : null;
      }
      const id = url.searchParams.get("v") ?? "";
      return isVideoId(id) ? id : null;
    }
    return null;
  } catch {
    return null;
  }
}

export async function fetchYouTubeTranscript(url: string): Promise<
  | { ok: true; text: string; language: string; autoGenerated: boolean; truncated: boolean }
  | { ok: false; error: string }
> {
  const videoId = youtubeVideoId(url);
  if (!videoId) {
    return { ok: false, error: "Video analysis currently supports YouTube links only." };
  }

  let player: Response;
  try {
    player = await fetch("https://www.youtube.com/youtubei/v1/player?prettyPrint=false", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "user-agent": "com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip",
        origin: "https://www.youtube.com",
      },
      body: JSON.stringify({
        context: {
          client: {
            clientName: "ANDROID",
            clientVersion: "20.10.38",
            androidSdkVersion: 30,
            hl: "en",
            gl: "AU",
          },
        },
        videoId,
      }),
    });
  } catch {
    return { ok: false, error: "Could not reach YouTube to read this video’s captions." };
  }

  if (!player.ok) {
    return { ok: false, error: "Could not reach YouTube to read this video’s captions." };
  }

  const payload = await player.json() as {
    playabilityStatus?: { status?: string; reason?: string };
    captions?: {
      playerCaptionsTracklistRenderer?: {
        captionTracks?: Array<{
          baseUrl?: string;
          languageCode?: string;
          kind?: string;
          name?: { simpleText?: string };
        }>;
      };
    };
  };

  if (payload.playabilityStatus?.status && payload.playabilityStatus.status !== "OK") {
    return {
      ok: false,
      error: payload.playabilityStatus.reason?.trim()
        || "This YouTube video is unavailable for caption analysis.",
    };
  }

  const tracks = payload.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  if (!tracks.length) {
    return {
      ok: false,
      error: "This YouTube video has no captions to analyse. Add a transcript excerpt in notes, or choose a video with captions.",
    };
  }

  const track = preferCaptionTrack(tracks);
  if (!track?.baseUrl) {
    return { ok: false, error: "Could not find a usable caption track for this video." };
  }

  const captionUrl = new URL(track.baseUrl);
  captionUrl.searchParams.set("fmt", "json3");
  let captions: Response;
  try {
    captions = await fetch(captionUrl.toString(), {
      headers: {
        "user-agent": "com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip",
      },
    });
  } catch {
    return { ok: false, error: "Could not download the video captions." };
  }
  if (!captions.ok) {
    return { ok: false, error: "Could not download the video captions." };
  }

  const body = await captions.json() as {
    events?: Array<{ segs?: Array<{ utf8?: string }> }>;
  };
  const text = cleanTranscript(
    (body.events ?? [])
      .flatMap((event) => (event.segs ?? []).map((seg) => seg.utf8 ?? ""))
      .join(" "),
  );
  if (!text) {
    return { ok: false, error: "The caption track for this video was empty." };
  }

  const truncated = text.length > MAX_TRANSCRIPT_CHARS;
  return {
    ok: true,
    text: text.slice(0, MAX_TRANSCRIPT_CHARS),
    language: track.languageCode || "und",
    autoGenerated: track.kind === "asr",
    truncated,
  };
}

function preferCaptionTrack(
  tracks: Array<{ baseUrl?: string; languageCode?: string; kind?: string }>,
) {
  const rank = (track: { languageCode?: string; kind?: string }) => {
    const lang = (track.languageCode || "").toLowerCase();
    const manual = track.kind === "asr" ? 1 : 0;
    if (lang === "en" || lang.startsWith("en-")) return manual;
    if (lang === "zh" || lang.startsWith("zh")) return 10 + manual;
    return 20 + manual;
  };
  return [...tracks].sort((a, b) => rank(a) - rank(b))[0] ?? null;
}

function cleanTranscript(value: string) {
  return value
    .replace(/[\u200b\u200c\u200d\ufeff]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function isVideoId(value: string) {
  return /^[\w-]{11}$/.test(value);
}
